# --- Install into one EasyEffects data directory -----------------------------

install_to() {
  local base="$1"
  mkdir -p "$base/irs" "$base/output" || return 1
  write_irs "$base/irs/$IRS_NAME.irs" || return 1
  write_preset "$base/output/$PRESET_NAME.json" || return 1
  # Sanity checks: files exist, are non-empty, and the IRS is a WAV (RIFF) file.
  [ -s "$base/output/$PRESET_NAME.json" ] || { echo "Preset file is empty: $base/output" >&2; return 1; }
  [ "$(head -c 4 "$base/irs/$IRS_NAME.irs" 2>/dev/null)" = "RIFF" ] \
    || { echo "Impulse response is invalid: $base/irs" >&2; return 1; }
}

# --- Detection ---------------------------------------------------------------

has_flatpak() {
  [ -d "$FLATPAK_BASE" ] ||
    { command -v flatpak >/dev/null 2>&1 && flatpak info "$FLATPAK_ID" >/dev/null 2>&1; }
}

has_system() {
  [ -d "$SYSTEM_BASE" ] || command -v easyeffects >/dev/null 2>&1
}

# --- Main --------------------------------------------------------------------

mode="auto"
assume_yes=false
for arg in "$@"; do
  case "$arg" in
    --flatpak|--system|--all) mode="$arg" ;;
    -y|--yes) assume_yes=true ;;
    -h|--help) sed -n '2,/^set /p' "$0" | sed '$d'; exit 0 ;;
    *) echo "Unknown option: $arg (try --help)" >&2; exit 2 ;;
  esac
done

do_flatpak=false
do_system=false
case "$mode" in
  --flatpak) do_flatpak=true ;;
  --system)  do_system=true ;;
  --all)     do_flatpak=true; do_system=true ;;
  auto)
    has_flatpak && do_flatpak=true
    has_system  && do_system=true
    ;;
esac

if ! $do_flatpak && ! $do_system; then
  echo "No EasyEffects installation detected; nothing installed." >&2
  echo "Install EasyEffects first, or re-run with --flatpak, --system or --all." >&2
  exit 1
fi

targets=()
labels=()
if $do_flatpak; then targets+=("$FLATPAK_BASE"); labels+=("Flatpak"); fi
if $do_system;  then targets+=("$SYSTEM_BASE");  labels+=("System package"); fi

echo "Output preset:               $PRESET_NAME"
echo "Convolver impulse response:  $IRS_NAME"
echo "Install location(s):"
for i in "${!targets[@]}"; do
  echo "  - ${labels[$i]}: ${targets[$i]}"
done
echo "Existing files with the same names will be overwritten."

if [ -t 0 ] && ! $assume_yes; then
  read -r -p "Continue? [y/N] " reply || exit 1
  [[ "$reply" =~ ^[Yy]$ ]] || { echo "Cancelled."; exit 0; }
fi

failed=0
for i in "${!targets[@]}"; do
  if out="$(install_to "${targets[$i]}" 2>&1)"; then
    echo "[ok]     ${labels[$i]}"
  else
    echo "[failed] ${labels[$i]}: ${out:-unknown error}" >&2
    failed=1
  fi
done

if [ "$failed" -ne 0 ]; then
  echo "Installation failed." >&2
  exit 1
fi

echo "Done. Restart EasyEffects if it is running, then select \"$PRESET_NAME\" under Output presets."
